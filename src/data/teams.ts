// Helper to look up team info by name or id
export function findTeam(query?: string | null): TeamInfo | undefined {
  if (!query) return undefined;
  const q = query.trim().toLowerCase();
  return TEAMS_DATABASE.find(
    (t) =>
      t.name.toLowerCase() === q ||
      t.enName.toLowerCase() === q ||
      t.id.toLowerCase() === q ||
      q.includes(t.name.toLowerCase()) ||
      t.name.toLowerCase().includes(q)
  );
}
